export interface Flashcard {
  id: string;
  front: string;
  frontImage?: CardImage;
  back: string;
  backImage?: CardImage;
  subjects: string[];
  examiners: string[];
  difficulty: Difficulty;
  customTags: string[];
  // Stabile, aufsteigende Nummer pro User. Einmal vergeben, nie geändert.
  // Für externe Referenzen ("Karte #42 in meinen Notizen").
  // Wird von der DB (Trigger assign_card_number) automatisch gesetzt.
  cardNumber?: number;
  // Multi-Set-Membership: eine Karte kann zu beliebig vielen Sets gehören.
  // Leeres Array = keinem Set zugeordnet. DB-Spalte: `set_ids text[]`.
  // (Migrations-Note: die alte `setId?: string`-Form wurde via
  //  supabase_migration_multi_sets.sql + Import-Backward-Compat ersetzt.)
  setIds: string[];
  flagged?: boolean;
  // "Parkiert" — explicitly excluded from all study pickers (daily plan,
  // Lernen, Prüfungsmodus, MC-Session). Card stays in Library with a
  // visual badge so the user can manage it; they can unparken anytime.
  // Different from `flagged` (which means "had trouble with it lately")
  // and different from priority C (which still shows up if you pick C).
  blacklisted?: boolean;
  // Priority for exam-prep focus mode.
  //   'A' = must know (must master before exam)
  //   'B' = should know
  //   'C' = nice to know
  //   undefined = not yet classified — treated as B for default filtering
  // Set either automatically via classifyPriority() heuristic or manually
  // by the user via the inline picker on card front.
  priority?: 'A' | 'B' | 'C';
  // True wenn der User die priority manuell über den Inline-Picker geändert
  // hat. Globale Re-Klassifizierungen (SQL-Migrations + Auto-Classify ohne
  // explicit-overwrite) respektieren dieses Flag und lassen die Karte in
  // Ruhe. Migrations siehe DEVELOPMENT.md.
  priorityLocked?: boolean;
  // Persistent MC questions for the MC-Lernmodus. Generated by AI once,
  // then cached forever (or until user regenerates manually). Adaptive
  // count: 3 for short cards, 5-7 for complex ones.
  // The format mirrors MCHintResult from src/utils/geminiMCHint.ts so we
  // can reuse the existing rendering widget.
  mcQuestions?: Array<{
    question: string;
    type: 'single' | 'multiple';
    options: Array<{ id: string; text: string; correct: boolean }>;
    explanation: string;
    topic: string;
  }>;
  mcQuestionsGeneratedAt?: string; // ISO timestamp — used to detect stale MC after card edits
  // Exam frequency / probability (set via JSON import)
  timesAsked?: number;
  askedByExaminers?: string[];
  askedInCatalogs?: string[];
  probabilityPercent?: number;
  createdAt: string; // ISO date string
  updatedAt: string; // ISO date string
  // SM-2 SRS fields
  interval: number;       // days until next review
  repetitions: number;    // number of successful reviews
  easeFactor: number;     // multiplier (default 2.5)
  nextReviewDate: string; // ISO date string
  // Set ONCE the first time a card crosses rep=0 → rep≥1 (i.e. the first
  // successful rating). Never updated after that, never touched by edits or
  // merges. This is the authoritative "when did this card stop being new?"
  // signal — used by the Dashboard reconciler so the "Neu heute" count is
  // independent of the snapshot's reliability.
  firstStudiedAt?: string;
}

export interface AppSettings {
  subjects: string[];
  examiners: string[];
  customTags: string[];
  studyStreak: number;
  lastStudiedDate: string | null;
  // Exam countdown & daily goal
  examDate?: string;        // ISO date string (YYYY-MM-DD)
  dailyNewCardGoal: number;   // default: 10
  // 'manual' = use dailyNewCardGoal as-is
  // 'auto'   = derive from unseen-in-focus / (daysUntilExam × 0.5), with
  //            the manual value as upper cap so the user retains control
  dailyNewCardGoalMode?: 'manual' | 'auto';
  dailyReviewCap: number;     // max reviews shown per day (default: 9999 = no cap)
  // Daily progress snapshot (resets each day)
  dailyPlanSnapshot?: {
    date: string;           // toDateString() key
    totalCards: number;     // size of plan when session was first started today
    newCardsDone: number;   // new cards already introduced today (persists across session breaks)
    totalDone: number;      // all cards rated ≥1 (Schwer/Gut/Einfach) today — for progress display
  };
  autoUnflagEnabled: boolean;        // remove flag after 2 correct days in Prüfungsmodus
  autoUnflagNotification?: {
    date: string;      // toDateString() key
    count: number;
    dismissed: boolean;
  };
  anthropicApiKey?: string;           // stored client-side for AI merge feature
  geminiApiKey?: string;              // stored client-side for AI card revision (Google AI Studio)
  groqApiKey?: string;               // stored client-side for Groq fallback (free, no credit card)
  studyOrder?: 'new-first' | 'review-first' | 'mixed'; // stored client-side
  // Focus-Modus: when set to 'A' or 'AB', the Dashboard + "Jetzt lernen" only
  // consider cards with that priority. Everything else (lower-priority cards)
  // is invisible until the user widens focus. The motivation engine: with
  // 1037 cards and 60 days to exam, retaining everything is impossible —
  // focusing on 200 must-know cards is realistic and gives a "done today"
  // feeling that the global view can't.
  focusMode?: 'all' | 'A' | 'AB';
  // Cross-device paused-session state. Mirror of the `studySession:state`
  // localStorage blob. Synced via user_settings so a session paused on the
  // phone shows up on the laptop. On restore: the newer (by pausedAt) wins
  // between local and remote.
  pausedSession?: PausedSession;
}

